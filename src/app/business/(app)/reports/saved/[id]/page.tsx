import { notFound } from "next/navigation";
import { PrintButton } from "@/components/business/report-forms";
import { Card, PageHeader, Pill, TableWrap } from "@/components/business/ui";
import { formatIsoDate } from "@/lib/business/calc";
import { requireBizContext } from "@/lib/server/business/context";
import { getSavedReport, type ReportMoney } from "@/lib/server/business/savings-report";

export const metadata = { title: "Savings report" };

const amounts = (list: ReportMoney[]) => (list.length ? list.map((m) => m.display).join(" · ") : "—");

function Basis({ children }: { children: React.ReactNode }) {
  return <p className="mt-2 text-[12px] leading-relaxed text-faint">{children}</p>;
}

export default async function SavedReportPage(props: { params: Promise<{ id: string }> }) {
  const { id } = await props.params;
  const ctx = await requireBizContext(`/business/reports/saved/${id}`);
  const saved = await getSavedReport(ctx, id);
  if (!saved) notFound();
  const r = saved.content;
  const fmt = ctx.workspace.dateFormat;
  return (
    <>
      <PageHeader
        title={r.title}
        crumbs={[{ label: "Reports", href: "/business/reports" }, { label: "Savings report" }]}
        description={`${r.workspaceName} · figures as of ${formatIsoDate(r.asOf, fmt)}${saved.source === "mcp" ? " · generated by an AI client (MCP)" : ""}. A snapshot: it doesn't change when records do.`}
        actions={<PrintButton />}
      />
      <div className="grid gap-5 md:grid-cols-3">
        <Card title="Software spend">
          <p className="tabular text-[1.3rem] font-semibold text-heading">{amounts(r.spend.monthly)}</p>
          <p className="text-[12.5px] text-muted">per month · {amounts(r.spend.annualized)} annualized</p>
          <p className="mt-1 text-[12.5px] text-muted">
            {r.spend.activeSubscriptions} active subscriptions{r.spend.withoutPrice ? ` · ${r.spend.withoutPrice} without a price` : ""}
          </p>
          <Basis>{r.spend.basis}</Basis>
        </Card>
        <Card title="Potential savings">
          <p className="tabular text-[1.3rem] font-semibold text-heading">{amounts(r.potential.annual)}</p>
          <p className="text-[12.5px] text-muted">
            per year · {r.potential.withEstimate} with an estimate, {r.potential.withoutEstimate} to check
          </p>
          <Basis>{r.potential.basis}</Basis>
        </Card>
        <Card title="Realized savings">
          <p className="tabular text-[1.3rem] font-semibold text-heading">{amounts(r.realized.firstYear)}</p>
          <p className="text-[12.5px] text-muted">first-year value of confirmed savings</p>
          <Basis>{r.realized.basis}</Basis>
        </Card>
      </div>

      <Card className="mt-5" title="Top opportunities" description="Open and under-review findings, largest estimate first.">
        {r.potential.top.length === 0 ? (
          <p className="text-[13.5px] text-muted">No open opportunities when this report was generated.</p>
        ) : (
          <ul className="divide-y divide-line">
            {r.potential.top.map((o) => (
              <li key={o.id} className="py-3">
                <div className="flex flex-wrap items-start justify-between gap-2">
                  <p className="text-[14px] font-medium text-fg">{o.title}</p>
                  <span className="tabular text-[13px] font-medium">{o.annualEstimate ? `${o.annualEstimate.display}/yr` : <span className="text-faint">No estimate</span>}</span>
                </div>
                <p className="mt-1 text-[12.5px] text-muted">
                  <Pill tone="outline" className="mr-1.5">
                    {o.type}
                  </Pill>
                  {o.recommendedAction} · confidence {o.confidence}
                </p>
                {o.evidence.length > 0 && (
                  <dl className="mt-1.5 flex flex-wrap gap-x-5 gap-y-1 text-[12px]">
                    {o.evidence.map((e) => (
                      <div key={e.label}>
                        <dt className="inline text-faint">{e.label}: </dt>
                        <dd className="inline text-fg">{e.value}</dd>
                      </div>
                    ))}
                  </dl>
                )}
              </li>
            ))}
          </ul>
        )}
        {r.potential.byType.length > 0 && <p className="mt-3 text-[12.5px] text-muted">By type: {r.potential.byType.map((t) => `${t.label} (${t.count})`).join(", ")}</p>}
      </Card>

      <Card className="mt-5" title={`Renewals in the next ${r.renewals.days} days`} description={`Expected: ${amounts(r.renewals.totals)}`}>
        {r.renewals.items.length === 0 ? (
          <p className="text-[13.5px] text-muted">No renewals in this window.</p>
        ) : (
          <TableWrap>
            <table className="biz-table">
              <thead>
                <tr>
                  <th>Software</th>
                  <th>Renews</th>
                  <th className="num">Expected</th>
                  <th>Auto-renew</th>
                  <th>Decision</th>
                </tr>
              </thead>
              <tbody>
                {r.renewals.items.map((x) => (
                  <tr key={`${x.subscriptionId}-${x.date}`}>
                    <td className="font-medium">{x.software}</td>
                    <td className="whitespace-nowrap">
                      {formatIsoDate(x.date, fmt)} <span className="text-faint">· {x.daysLeft}d</span>
                    </td>
                    <td className="num">{x.amount?.display ?? "—"}</td>
                    <td>{x.autoRenew ? "Yes" : "No"}</td>
                    <td className="capitalize">{x.decision}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </TableWrap>
        )}
        <Basis>{r.renewals.basis}</Basis>
      </Card>

      {r.realized.entries.length > 0 && (
        <Card className="mt-5" title="Confirmed savings">
          <ul className="space-y-1.5 text-[13px]">
            {r.realized.entries.map((e, i) => (
              <li key={i} className="flex flex-wrap justify-between gap-2">
                <span>
                  {e.description} <span className="text-faint">· {formatIsoDate(e.confirmedOn, fmt)}</span>
                </span>
                <span className="tabular font-medium">
                  {e.amount.display} {e.recurrence === "one_time" ? "once" : e.recurrence}
                </span>
              </li>
            ))}
          </ul>
        </Card>
      )}

      <div className="mt-5 grid gap-5 md:grid-cols-2">
        <Card title="Data quality">
          {r.dataQuality.length === 0 ? <p className="text-[13.5px] text-muted">No gaps found.</p> : <ul className="list-disc space-y-1 pl-5 text-[13px] text-muted">{r.dataQuality.map((q) => <li key={q}>{q}</li>)}</ul>}
        </Card>
        <Card title="Method">
          <ul className="list-disc space-y-1 pl-5 text-[13px] text-muted">
            {r.method.map((m) => (
              <li key={m}>{m}</li>
            ))}
          </ul>
        </Card>
      </div>
    </>
  );
}
